create table public.movies (
    id bigint generated by default as identity primary key,
    title text not null,
    genre text not null,
    year integer not null check (year >= 1888 and year <= 2100),
    watched boolean not null default false,
    created_at timestamptz not null default now()
);

alter table public.movies enable row level security;

grant select, insert, update, delete on public.movies to anon;
grant usage, select on sequence public.movies_id_seq to anon;

create policy "Permitir leitura de filmes"
on public.movies
for select
to anon
using (true);

create policy "Permitir cadastro de filmes"
on public.movies
for insert
to anon
with check (true);

create policy "Permitir atualização de filmes"
on public.movies
for update
to anon
using (true)
with check (true);

create policy "Permitir exclusão de filmes"
on public.movies
for delete
to anon
using (true);

